-- ============================================================================
-- MENU MASTER NG
-- 0037: make "the latest cost snapshot" deterministic
--
-- Requires: 0001-0036 applied.
--
-- THE DEFECT (P1, financial)
--   Every view that resolves a recipe's current cost does
--       distinct on (recipe_id) ... order by recipe_id, computed_at desc
--   and computed_at defaults to now(), which in PostgreSQL is TRANSACTION
--   START. Two snapshots written for the same recipe inside one transaction
--   therefore carry an IDENTICAL timestamp, the ordering is a tie, and which
--   row wins is arbitrary.
--
--   Proven on the replica: a recipe costed at N850/portion, then given an
--   unpriced ingredient and recomputed in the same transaction, still reported
--   is_complete = true, a N650 profit and a 43.33% margin -- profit and margin
--   for a recipe whose cost the engine had just refused to compute. That is a
--   silent financial fallback of exactly the kind this product forbids.
--
--   It is reachable in normal use, not only in tests. fn_post_purchase writes
--   one ingredient_prices row per line inside a single transaction, and
--   ingredient_prices carries a recompute trigger (0008). A market run buying
--   two ingredients that appear in the same recipe recomputes that recipe
--   twice in one transaction and ties.
--
-- SECURITY_INVOKER IS RESTATED ON EVERY VIEW BELOW, DELIBERATELY.
--   CREATE OR REPLACE VIEW does not preserve reloptions. Omitting
--   `with (security_invoker = on)` silently RESETS it and the view then runs
--   with the definer's rights, reading across tenants. An earlier draft of
--   this migration did exactly that on all four views; tests/023 caught the
--   cross-tenant read. A definition fingerprint does NOT detect it, because
--   pg_views.definition excludes reloptions -- which is why the self-check
--   below asserts the option itself on every view touched.
--
-- THE FIX
--   cost_snapshots gains an identity column, seq, which is monotonic within
--   and across transactions. Every "latest" ordering becomes
--       order by ... computed_at desc, seq desc
--   so the newest row always wins and the result is deterministic.
--
--   Additive and non-destructive: no snapshot is altered or deleted, and the
--   costing arithmetic is untouched. Rows written before this migration are
--   assigned seq values in whatever order the table is scanned; for those,
--   computed_at remains the primary ordering exactly as before, so their
--   relative order is unchanged except where they already tied -- and where
--   they tied, no correct order existed to preserve.
-- ============================================================================

do $$
begin
  if not exists (select 1 from pg_class where relname = 'cost_snapshots') then
    raise exception '0037 preflight FAILED: cost_snapshots is missing.';
  end if;
  if exists (select 1 from information_schema.columns
              where table_name = 'cost_snapshots' and column_name = 'seq') then
    raise exception '0037 preflight FAILED: cost_snapshots.seq already exists.';
  end if;
  if not exists (select 1 from information_schema.columns
                  where table_name = 'v_price_check' and column_name = 'markup_pct') then
    raise exception '0037 preflight FAILED: 0036 must be applied first.';
  end if;
  if (select count(*) from pg_policies where schemaname = 'public') <> 116 then
    raise exception '0037 preflight FAILED: policy count is %, expected 116.',
      (select count(*) from pg_policies where schemaname = 'public');
  end if;
end
$$;

alter table cost_snapshots
  add column seq bigint generated by default as identity;

comment on column cost_snapshots.seq is
  'Monotonic tie-breaker. computed_at is now(), which is transaction start, so '
  'two snapshots written in one transaction share a timestamp; seq makes '
  '"latest" deterministic. Never used in any cost calculation.';

create or replace view v_recipe_cost_current with (security_invoker = on) as
 SELECT DISTINCT ON (recipe_id) id,
    account_id,
    business_id,
    recipe_id,
    computed_at,
    costing_method,
    wavg_window_days,
    is_complete,
    required_inputs,
    priced_inputs,
    excluded_inputs,
    unpriced_items,
    ingredient_cost,
    packaging_cost,
    labour_cost,
    overhead_cost,
    batch_cost,
    cost_per_yield_unit,
    cost_per_portion,
    created_by
   FROM cost_snapshots
  ORDER BY recipe_id, computed_at DESC, seq DESC;

create or replace view v_price_check with (security_invoker = on) as
 WITH recipe_latest AS (
         SELECT DISTINCT ON (cost_snapshots.recipe_id) cost_snapshots.id,
            cost_snapshots.account_id,
            cost_snapshots.business_id,
            cost_snapshots.recipe_id,
